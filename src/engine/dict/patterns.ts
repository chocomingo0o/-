/**
 * 문장 성격을 가르는 단서 사전.
 *
 * - REFLECT_TERMS : 성찰·개선 단서(한계, 오차, 개선, 재실험 …) → Sent.rf, 깊이 4단계 판정
 * - CONNECT_TERMS : 앞 기록(지난 학기, 1학년 때 …)을 끌어오는 단서 → Rec.connectCue
 * - FOLLOW_TERMS  : 같은 기록 안에서 뒤따르는 추가 탐구 단서 → Sent.fu
 * - INQ_TERMS     : 탐구 행위 동사·명사 → 문장 점수 +1
 * - EVAL_WORDS    : 평가·태도 어휘. 행위 동사(ACTION_VERBS)가 없으면 평가 문장으로 본다.
 * - EVAL_SENT     : 문장 전체가 평가 문장인지
 * - EVAL_TAIL     : 문장 끝 평가 꼬리(요약할 때 떼어 낸다)
 * - LEAD_ADVERBS  : 문장 앞 접속어·부사(요약할 때 떼어 낸다)
 *
 * 모든 *_TERMS 항목은 정규식 조각(소스 문자열)이다. 공백은 '\s*'로 적어 띄어쓰기 차이를 흡수한다.
 * TypeScript 문자열 안이므로 역슬래시는 두 번('\\s*') 쓴다.
 * 이 파일은 DOM에 의존하지 않는다.
 */

/** 정규식 조각 배열을 하나의 RegExp로 만든다. 기본 플래그는 'g'. test()에 쓸 때는 ''를 넘기는 편이 안전하다. */
export function rx(terms: string[], flags: string = 'g'): RegExp {
  return new RegExp('(?:' + terms.join('|') + ')', flags);
}

