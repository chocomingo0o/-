/** 흔한 낱말 가중치. 흔할수록 0.25에 가깝고, 사전에 없으면 1. */
export function commonWeight(t: string): number {
  const raw = Object.prototype.hasOwnProperty.call(COMMON, t) ? COMMON[t] : 0;
  const c = typeof raw === 'number' && Number.isFinite(raw) ? Math.min(1, Math.max(0, raw)) : 0;
  return 0.25 + 0.75 * (1 - c);
}
